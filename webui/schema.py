def schema_payload() -> dict[str, Any]:
    return {
        "tasks": TASKS,
        "objects": OBJECT_PRESETS,
        "hand_poses": HAND_POSES,
        "physics": PHYSICS_BACKENDS,
        "cameras": CAMERA_LAYOUTS,
        "groups": GROUPS_ORDER,
        "params": [p.to_dict() for p in PARAMS],
        "sandbox": sandbox_schema(),
    }


def params_markdown() -> str:
    """Render the catalog as a Chinese markdown encyclopedia."""
    lines = [
        "# 训练参数百科",
        "",
        "本文由 `webui/schema.py` 生成，和界面上的 ⓘ 是同一份解释。改参数说明请改 schema，不要只改这个文件。",
        "",
    ]
    by_group: dict[str, list[Param]] = {g: [] for g in GROUPS_ORDER}
    for p in PARAMS:
        by_group.setdefault(p.group, []).append(p)
    for group in GROUPS_ORDER:
        lines.append(f"## {group}")
        lines.append("")
        for p in by_group.get(group, []):
            lines.append(f"### {p.label}")
            lines.append("")
            lines.append(f"- **路径**：`{p.path}`（{p.kind}）")
            lines.append(f"- **默认**：`{p.default}`")
            lines.append(f"- **作用**：{p.summary}")
            lines.append(f"- **调大**：{p.bigger}")
            lines.append(f"- **调小**：{p.smaller}")
            lines.append(f"- **新手**：{p.novice}")
            lines.append("")
    return "\n".join(lines)
