    min: float | None = None
    max: float | None = None
    step: float | None = None
    options: list[str] = field(default_factory=list)
    tasks: list[str] = field(default_factory=list)
    advanced: bool = False

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


